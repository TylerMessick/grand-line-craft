package com.messickmedia.grandline.client;

import com.messickmedia.grandline.GrandLine;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.Model;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.util.Mth;

import javax.annotation.Nullable;
import java.util.HashMap;
import java.util.Map;

/**
 * The azure dragon. The rig (DragonLayer) is generated by gen/gen_dragon.py; this class animates it: a travelling
 * wave down neck, body and tail, the head following the look, the jaw working, whiskers and mane drifting, the arms
 * paddling in flight, the tail tuft flicking.
 */
public class DragonModel extends Model {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(GrandLine.id("seiryu_dragon"), "main");

    private final ModelPart root;
    private final Map<String, ModelPart> parts = new HashMap<>();

    public DragonModel(ModelPart root) {
        super(RenderType::entityCutoutNoCull);
        this.root = root;
        for (String n : DragonLayer.PART_NAMES) {
            ModelPart p = find(root, n);
            if (p != null) this.parts.put(n, p);
        }
    }

    public static LayerDefinition createLayer() {
        return DragonLayer.create();
    }

    @Nullable
    private static ModelPart find(ModelPart p, String name) {
        if (p.hasChild(name)) return p.getChild(name);
        for (String n : DragonLayer.PART_NAMES) {
            if (p.hasChild(n)) {
                ModelPart r = find(p.getChild(n), name);
                if (r != null) return r;
            }
        }
        return null;
    }

    private void rot(String name, float x, float y, float z) {
        ModelPart p = this.parts.get(name);
        if (p == null) return;
        p.xRot += x;
        p.yRot += y;
        p.zRot += z;
    }

    /** Procedural animation. speed: horizontal blocks per tick; pitch in degrees; flying while off the ground. */
    public void setup(float age, float speed, float pitchDeg, boolean flying) {
        this.root.getAllParts().forEach(ModelPart::resetPose);
        float w = age * 0.11F;
        float amp = 0.09F + Math.min(0.14F, speed * 0.5F);
        // the body: each segment bends a little further along the wave, so the chain reads as one serpent
        for (int i = 0; i < 5; i++) {
            rot("body" + i, Mth.cos(w * 0.9F - i * 0.65F) * amp * 0.45F, Mth.sin(w - i * 0.65F) * amp, 0);
        }
        for (int i = 0; i < 8; i++) {
            rot("tail" + i, Mth.cos(w * 0.9F - (5 + i) * 0.65F) * amp * 0.55F, Mth.sin(w - (5 + i) * 0.65F) * (amp + 0.04F), 0);
        }
        rot("tail_tuft", Mth.sin(age * 0.25F) * 0.3F, Mth.cos(age * 0.2F) * 0.25F, 0);
        // neck and head follow the look; a slow breathing bob
        float pitch = pitchDeg * Mth.DEG_TO_RAD;
        float bob = Mth.sin(age * 0.07F) * 0.05F;
        rot("neck0", pitch * 0.2F - 0.12F + bob, Mth.sin(w + 0.7F) * amp * 0.6F, 0);
        rot("neck1", pitch * 0.25F - 0.08F + bob, Mth.sin(w + 1.3F) * amp * 0.4F, 0);
        rot("neck2", pitch * 0.25F + 0.15F, 0, 0);
        rot("head", pitch * 0.3F + 0.05F, 0, 0);
        rot("jaw", 0.12F + 0.1F * Mth.sin(age * 0.09F) + (flying ? 0.08F : 0.0F), 0, 0);
        rot("horn_l", Mth.sin(age * 0.05F) * 0.03F, 0, 0);
        rot("horn_r", Mth.sin(age * 0.05F) * 0.03F, 0, 0);
        rot("ear_l", 0, 0, Mth.sin(age * 0.13F) * 0.15F);
        rot("ear_r", 0, 0, -Mth.sin(age * 0.13F) * 0.15F);
        // arms: paddling strokes in flight, a walking cycle on the ground
        float stroke = flying ? Mth.sin(age * 0.18F) * 0.55F : Mth.sin(age * 0.5F) * Math.min(1.0F, speed * 3.0F) * 0.8F;
        rot("leg_fl", -0.4F + stroke, 0, 0);
        rot("leg_fr", -0.4F - stroke, 0, 0);
        rot("leg_bl", -0.3F - stroke, 0, 0);
        rot("leg_br", -0.3F + stroke, 0, 0);
        float curl = 0.6F + 0.3F * Mth.sin(age * 0.18F + 1.0F);
        rot("leg_fl_low", curl, 0, 0);
        rot("leg_fr_low", curl, 0, 0);
        rot("leg_bl_low", curl, 0, 0);
        rot("leg_br_low", curl, 0, 0);
        rot("leg_fl_foot", -0.5F, 0, 0);
        rot("leg_fr_foot", -0.5F, 0, 0);
        rot("leg_bl_foot", -0.5F, 0, 0);
        rot("leg_br_foot", -0.5F, 0, 0);
        if (flying) rot("body0", pitch * 0.45F, 0, 0);
    }

    @Override
    public void renderToBuffer(PoseStack ps, VertexConsumer vc, int light, int overlay, int color) {
        this.root.render(ps, vc, light, overlay, color);
    }
}
